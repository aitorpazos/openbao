const (
	replicationPerformanceConfigPath = "core/replication/performance"
	replicationDRConfigPath          = "core/replication/dr"
	replicationKeyPath               = "core/replication/keys/"

	// replicationMerkleWalkLimit bounds the merkle-root storage walk so an
	// unbounded cluster cannot stall status. Enterprise maintains an
	// incrementally indexed tree; this implementation recomputes on demand
	// (documented deviation).
	replicationMerkleWalkLimit = 100_000
)

// replicationModeState is the persisted state for one replication stream
// (performance or DR). It is stored under the barrier root so it survives
// seal/unseal cycles like other core state.
type replicationModeState struct {
	// Mode is one of "primary", "secondary", "demoted".
	Mode string `json:"mode"`
	// State is the coarse stream state ("running" in phase 1; streaming
	// sub-states arrive with WAL streaming).
	State string `json:"state"`

	// ClusterID is the replication-set identifier. On a primary this is the
	// local cluster ID; on a secondary it is learned from the activation
	// token (i.e. the primary's cluster ID), matching the documented status
	// samples where primary and secondary report the same cluster_id.
	ClusterID string `json:"cluster_id"`

	PrimaryClusterAddr string `json:"primary_cluster_addr,omitempty"`

	// SecondaryID is the identifier this node was activated with (secondary
	// mode only).
	SecondaryID string `json:"secondary_id,omitempty"`

	// KnownSecondaries maps secondary identifiers to the (possibly empty)
	// public key supplied at token generation.
	KnownSecondaries map[string]string `json:"known_secondaries,omitempty"`

	// KnownPrimaryClusterAddrs is the address list supplied via
	// update-primary's update_primary_addrs parameter.
	KnownPrimaryClusterAddrs []string `json:"known_primary_cluster_addrs,omitempty"`

	LastStart        string `json:"last_start,omitempty"`
	LastReindexEpoch int64  `json:"last_reindex_epoch,omitempty"`

	// PathsFilters applies to performance replication only (documented:
	// the DR surface has no paths-filter endpoints).
	PathsFilters map[string]replicationPathsFilter `json:"paths_filters,omitempty"`

	// SecondaryPublicKey is the PEM/DER blob generated by
	// secondary/generate-public-key, base64-encoded, with the private key
	// stored alongside for credential encryption in a later phase.
	SecondaryPublicKey string `json:"secondary_public_key,omitempty"`
}

type replicationPathsFilter struct {
	Mode  string   `json:"mode"`
	Paths []string `json:"paths"`
}

// replicationStateFile is the on-disk envelope for one stream.
type replicationStateFile struct {
	State *replicationModeState `json:"state"`
}

// loadReplicationModeState reads the persisted state for a stream. A missing
// entry means the stream is disabled (nil, nil).
func (c *Core) loadReplicationModeState(ctx context.Context, path string) (*replicationModeState, error) {
	entry, err := c.barrier.Get(ctx, path)
	if err != nil {
		return nil, err
	}
	if entry == nil {
		return nil, nil
	}
	var f replicationStateFile
	if err := json.Unmarshal(entry.Value, &f); err != nil {
		return nil, err
	}
	if f.State != nil {
		// Normalize collections after deserialization; omitempty fields
		// unmarshal as nil maps/slices and callers assign into them.
		if f.State.KnownSecondaries == nil {
			f.State.KnownSecondaries = map[string]string{}
		}
		if f.State.PathsFilters == nil {
			f.State.PathsFilters = map[string]replicationPathsFilter{}
		}
	}
	return f.State, nil
}

func (c *Core) saveReplicationModeState(ctx context.Context, path string, st *replicationModeState) error {
	if st == nil {
		return c.barrier.Delete(ctx, path)
	}
	if st.PathsFilters == nil {
		st.PathsFilters = map[string]replicationPathsFilter{}
	}
	if st.KnownSecondaries == nil {
		st.KnownSecondaries = map[string]string{}
	}
	buf, err := json.Marshal(&replicationStateFile{State: st})
	if err != nil {
		return err
	}
	return c.barrier.Put(ctx, &logical.StorageEntry{
		Key:   path,
		Value: buf,
	})
}

// computeReplicationConstsState derives the consts.ReplicationState flag set
// from the persisted configuration. It mirrors the community defaults when
// both streams are disabled so stock deployments keep their existing
// sys/health behavior.
func (c *Core) computeReplicationConstsState(perf *replicationModeState, dr *replicationModeState, active bool) consts.ReplicationState {
	var ret consts.ReplicationState

	switch {
	// No performance replication config in barrier state. Mirror the
	// pre-existing in-tree semantics: a node of a non-replicated cluster
	// still reports PerformancePrimary when active and PerformanceStandby
	// when a standby. This matters for request forwarding: paths marked
	// ForwardPerformanceStandby (e.g. sys/mfa/validate) are forwarded
	// before their callbacks run whenever the processing node carries the
	// ReplicationPerformanceStandby flag; reporting PerformanceDisabled
	// here would make plain standbys execute those paths locally against
	// read-only storage.
	case perf == nil:
		if active {
			ret.AddState(consts.ReplicationPerformancePrimary)
		} else {
			ret.AddState(consts.ReplicationPerformanceStandby)
		}
	case perf.Mode == "primary":
		if active {
			ret.AddState(consts.ReplicationPerformancePrimary)
		} else {
			ret.AddState(consts.ReplicationPerformanceStandby)
		}
	case perf.Mode == "secondary":
		ret.AddState(consts.ReplicationPerformanceSecondary)
	default:
		ret.AddState(consts.ReplicationPerformanceDisabled)
	}

	switch {
	case dr == nil:
		ret.AddState(consts.ReplicationDRDisabled)
	case dr.Mode == "primary":
		ret.AddState(consts.ReplicationDRPrimary)
	case dr.Mode == "secondary":
		ret.AddState(consts.ReplicationDRSecondary)
	default:
		ret.AddState(consts.ReplicationDRDisabled)
	}

	return ret
}

// refreshReplicationStateConsts recomputes and stores the consts replication
// state from the persisted configuration. active indicates whether this node
// is the active (leader) node; standby nodes report the standby component.
// It does not require c.stateLock; the atomic store makes concurrent updates
// benign and the barrier is internally synchronized.
func (c *Core) refreshReplicationStateConsts(ctx context.Context, active bool) error {
	if c.barrier == nil {
		// During CreateCore the barrier is not yet attached; the community
		// default (both streams disabled) is correct until unseal.
		return errors.New("barrier not initialized")
	}
	perf, err := c.loadReplicationModeState(ctx, replicationPerformanceConfigPath)
	if err != nil {
		return err
	}
	dr, err := c.loadReplicationModeState(ctx, replicationDRConfigPath)
	if err != nil {
		return err
	}

	c.replicationState.Store(uint32(c.computeReplicationConstsState(perf, dr, active)))
	return nil
}

// replicationSecondaryKeyPair returns (or lazily creates) the secondary
// public/private key pair used to encrypt activation credentials without a
// round trip to the primary.
func (c *Core) replicationSecondaryKeyPair(ctx context.Context, modePath string) (pubB64 string, err error) {
	c.replicationStateMut.Lock()
	defer c.replicationStateMut.Unlock()

	st, err := c.loadReplicationModeState(ctx, modePath)
	if err != nil {
		return "", err
	}
	if st != nil && st.SecondaryPublicKey != "" {
		return st.SecondaryPublicKey, nil
	}

	key, err := ecdsa.GenerateKey(elliptic.P256(), rand.Reader)
	if err != nil {
		return "", err
	}
	der, err := x509.MarshalPKIXPublicKey(&key.PublicKey)
	if err != nil {
		return "", err
	}

	pub := base64.StdEncoding.EncodeToString(der)
	if st == nil {
		// Stream disabled: return an ephemeral key without persisting any
		// state (repeated calls on a disabled stream yield fresh keys).
		return pub, nil
	}
	st.SecondaryPublicKey = pub
	if err := c.saveReplicationModeState(ctx, modePath, st); err != nil {
		return "", err
	}
	return st.SecondaryPublicKey, nil
}

// merkleRoot walks the barrier storage and computes a deterministic hash over
// all keys and values. This mirrors the purpose of the Enterprise merkle
// index (documented deviation: full walk instead of an incrementally
// maintained index tree).
func (c *Core) merkleRoot(ctx context.Context) (string, error) {
	h := sha256.New()
	count := 0

	var walk func(prefix string) error
	walk = func(prefix string) error {
		keys, err := c.barrier.List(ctx, prefix)
		if err != nil {
			return err
		}
		for _, k := range keys {
			full := prefix + k
			if strings.HasSuffix(k, "/") {
				if err := walk(full); err != nil {
					return err
				}
				continue
			}
			count++
			if count > replicationMerkleWalkLimit {
				return fmt.Errorf("merkle walk limit exceeded (%d keys)", replicationMerkleWalkLimit)
			}
			entry, err := c.barrier.Get(ctx, full)
			if err != nil {
				// Some legacy/rotation entries cannot be decrypted under
				// the current keyring; the merkle index tolerates this by
				// skipping them (documented deviation).
				c.logger.Debug("skipping undecryptable entry in merkle walk", "path", full, "error", err)
				continue
			}
			if entry == nil {
				continue
			}
			h.Write([]byte(full))
			h.Write([]byte{0})
			sum := sha256.Sum256(entry.Value)
			h.Write(sum[:])
		}
		return nil
	}

	if err := walk(""); err != nil {
		return "", err
	}
	return fmt.Sprintf("%x", h.Sum(nil)), nil
}

// zeroEpochString is the documented sentinel for "no corruption check has
// run yet" (-62135596800 is the Unix timestamp of time.Time{}).
var zeroEpochString = strconv.FormatInt(time.Time{}.Unix(), 10)

// replicationStatus builds the documented status stanza for one stream.
// Nil (disabled) yields an empty map; callers omit disabled stanzas for
// /sys/replication/status and return an empty object on the typed status
// endpoints.
func (c *Core) replicationStatus(ctx context.Context, st *replicationModeState, walLabel string) (map[string]any, error) {
	out := map[string]any{}
	if st == nil {
		return out, nil
	}

	root, err := c.merkleRoot(ctx)
	if err != nil {
		return nil, err
	}

	out["cluster_id"] = st.ClusterID
	out["corrupted_merkle_tree"] = false
	out["last_corruption_check_epoch"] = zeroEpochString
	if st.LastReindexEpoch <= 0 {
		out["last_reindex_epoch"] = zeroEpochString
	} else {
		out["last_reindex_epoch"] = strconv.FormatInt(st.LastReindexEpoch, 10)
	}
	out["merkle_root"] = root
	out["ssct_generation_counter"] = 0

	switch st.Mode {
	case "primary":
		out["mode"] = "primary"
		out["state"] = "running"
		out["primary_cluster_addr"] = st.PrimaryClusterAddr
		out["last_wal"] = c.replicationLastWAL()
		out[walLabel] = c.replicationLastWAL()
		known := make([]string, 0, len(st.KnownSecondaries))
		for id := range st.KnownSecondaries {
			known = append(known, id)
		}
		out["known_secondaries"] = known
		// Phase 1: no live secondary connections exist, so no per-secondary
		// connection entries are reported (documented deviation).
		out["secondaries"] = []map[string]any{}
	case "secondary", "demoted":
		out["mode"] = "secondary"
		out["state"] = st.State
		out["connection_state"] = "ready"
		out["primary_cluster_addr"] = st.PrimaryClusterAddr
		out["secondary_id"] = st.SecondaryID
		out["last_remote_wal"] = c.replicationLastWAL()
		out["last_start"] = st.LastStart
		out["known_primary_cluster_addrs"] = st.KnownPrimaryClusterAddrs
		primaries := []map[string]any{}
		if st.PrimaryClusterAddr != "" {
			primaries = append(primaries, map[string]any{
				"api_address":         st.PrimaryClusterAddr,
				"cluster_address":     st.PrimaryClusterAddr,
				"connection_status":   "disconnected",
				"last_heartbeat":      "",
				"clock_skew_ms":       "0",
				"last_heartbeat_duration_ms": "0",
			})
		}
		out["primaries"] = primaries
	}

	return out, nil
}

// replicationLastWAL reports the storage's last applied index. On raft
// backends this is the raft applied index; on other backends it is 0.
func (c *Core) replicationLastWAL() int {
	if raft := c.GetRaftBackend(); raft != nil {
		return int(raft.AppliedIndex())
	}
	return 0
}

// replicationActivationData is the payload carried inside a secondary
// activation token (wrapped via the existing response-wrapping machinery).
type replicationActivationData struct {
	ClusterID  string `json:"cluster_id"`
	ClusterAddr string `json:"cluster_addr"`
	ID         string `json:"id"`
	Mode       string `json:"mode"` // performance | dr
}

// activateSecondary unwraps an activation token and applies it. Two token
// shapes are supported:
//   - an in-cluster response-wrapping token (unwrapped against the local
//     token store / cubbyhole — the unit-test and single-cluster path);
//   - a JWT wrapping token minted by the primary (Enterprise semantics):
//     the JWT is parsed without signature verification to read its `addr`
//     claim, and the wrapped payload is fetched by POSTing the token to
//     `<addr>/v1/sys/wrapping/unwrap` on the primary. Signature verification
//     against the primary's published key is deferred to the streaming
//     phase (documented deviation).
func (c *Core) activateSecondary(ctx context.Context, token, primaryAPIAddr string) (*replicationActivationData, error) {
	if token == "" {
		return nil, errors.New("token is required")
	}

	// JWT-shaped tokens (three dot-separated parts) are the Enterprise
	// activation format; anything else goes through the local wrapping
	// token path.
	if strings.Count(token, ".") == 2 {
		return c.activateSecondaryFromJWT(ctx, token, primaryAPIAddr)
	}
	te, err := c.tokenStore.lookupTainted(ctx, token)
	if err != nil {
		return nil, err
	}
	if te == nil {
		return nil, errors.New("token is not a valid secondary activation token")
	}
	return c.activateSecondaryFromLocalToken(ctx, token, te, primaryAPIAddr)
}

func (c *Core) activateSecondaryFromLocalToken(ctx context.Context, token string, te *logical.TokenEntry, primaryAPIAddr string) (*replicationActivationData, error) {
	if len(te.Policies) != 1 || te.Policies[0] != vpol.ResponseWrappingPolicyName {
		return nil, errors.New("token is not a valid secondary activation token")
	}

	if c.systemBackend == nil {
		return nil, errors.New("system backend not initialized")
	}
	response, err := c.systemBackend.responseWrappingUnwrap(ctx, te, true)
	if err != nil {
		return nil, err
	}

	httpResp := &logical.HTTPResponse{}
	if err := jsonutil.DecodeJSON([]byte(response), httpResp); err != nil {
		return nil, fmt.Errorf("error decoding activation token: %w", err)
	}

	d := httpResp.Data
	if d == nil {
		return nil, errors.New("activation token payload is missing activation data")
	}
	return replicationActivationDataFromMap(d, primaryAPIAddr)
}

// activateSecondaryFromJWT implements the cross-cluster activation flow: the
// JWT wrapping token carries the primary's API address in its `addr` claim;
// the payload is fetched from the primary via sys/wrapping/unwrap.
func (c *Core) activateSecondaryFromJWT(ctx context.Context, token, primaryAPIAddr string) (*replicationActivationData, error) {
	parts := strings.Split(token, ".")
	if len(parts) != 3 {
		return nil, errors.New("token is not a valid secondary activation token")
	}
	payload, err := base64.RawURLEncoding.DecodeString(parts[1])
	if err != nil {
		return nil, errors.New("token is not a valid secondary activation token")
	}
	var claims struct {
		JTI string `json:"jti"`
		EXP int64  `json:"exp"`
		Type string `json:"type"`
		Addr string `json:"addr"`
	}
	if err := json.Unmarshal(payload, &claims); err != nil {
		return nil, errors.New("token is not a valid secondary activation token")
	}
	if claims.Type != "wrapping" {
		return nil, errors.New("token is not a valid secondary activation token")
	}
	if claims.EXP > 0 && time.Now().Unix() > claims.EXP {
		return nil, errors.New("activation token is expired")
	}

	// No addr claim (single-cluster environments): unwrap locally via the
	// JWT's jti (the wrapping-token ID).
	if claims.Addr == "" {
		if c.tokenStore == nil {
			return nil, errors.New("token store not initialized")
		}
		te, terr := c.tokenStore.lookupTainted(ctx, claims.JTI)
		if terr != nil || te == nil {
			return nil, errors.New("token is not a valid secondary activation token")
		}
		return c.activateSecondaryFromLocalToken(ctx, claims.JTI, te, primaryAPIAddr)
	}

	unwrapAddr := strings.TrimSuffix(claims.Addr, "/")
	unwrapAddr = unwrapAddr + "/v1/sys/wrapping/unwrap"
	httpReq, err := http.NewRequestWithContext(ctx, http.MethodPost, unwrapAddr, nil)
	if err != nil {
		return nil, err
	}
	httpReq.Header.Set("X-Vault-Token", token)

	httpClient := &http.Client{Timeout: 10 * time.Second}
	httpRespRaw, err := httpClient.Do(httpReq)
	if err != nil {
		return nil, fmt.Errorf("error unwrapping activation token against the primary: %w", err)
	}
	defer httpRespRaw.Body.Close()
	body, err := io.ReadAll(httpRespRaw.Body)
	if err != nil {
		return nil, err
	}
	if httpRespRaw.StatusCode != http.StatusOK {
		return nil, fmt.Errorf("error unwrapping activation token against the primary: %s", http.StatusText(httpRespRaw.StatusCode))
	}

	var envelope struct {
		Data map[string]any `json:"data"`
	}
	if err := json.Unmarshal(body, &envelope); err != nil {
		return nil, fmt.Errorf("error decoding activation token: %w", err)
	}
	if envelope.Data == nil {
		return nil, errors.New("activation token payload is missing activation data")
	}
	return replicationActivationDataFromMap(envelope.Data, primaryAPIAddr)
}

func replicationActivationDataFromMap(d map[string]any, primaryAPIAddr string) (*replicationActivationData, error) {
	act := &replicationActivationData{
		ClusterID:   strVal(d["cluster_id"]),
		ClusterAddr: strVal(d["cluster_addr"]),
		ID:          strVal(d["id"]),
		Mode:        strVal(d["mode"]),
	}
	if act.ClusterID == "" {
		return nil, errors.New("activation token payload is missing cluster_id")
	}

	if primaryAPIAddr != "" {
		act.ClusterAddr = primaryAPIAddr
	}
	return act, nil
}

func strVal(v any) string {
	s, _ := v.(string)
	return s
}
